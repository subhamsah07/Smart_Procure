export const normalizeLanguage = (lang?: string | null): SupportedLanguage => {
  if (!lang) return 'en';
  const code = lang.split('-')[0].toLowerCase();
  return (['en', 'hi', 'pa', 'bn'].includes(code) ? code : 'en') as SupportedLanguage;
};

const getInitialLanguage = (): SupportedLanguage => {
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem('smartprocure_language') || localStorage.getItem('i18nextLng');
      if (saved) {
        return normalizeLanguage(saved);
      }
    } catch {
      // ignore storage errors
    }
  }
  return 'en';
};

const initialLang = getInitialLanguage();

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLang,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
    react: {
      useSuspense: false,
      bindI18n: 'languageChanged loaded',
      bindI18nStore: 'added removed',
    },
  });

if (typeof window !== 'undefined') {
  i18n.on('languageChanged', (lng) => {
    try {
      const normalized = normalizeLanguage(lng);
      localStorage.setItem('smartprocure_language', normalized);
      localStorage.setItem('i18nextLng', normalized);
    } catch {
      // ignore storage errors
    }
  });
}

export default i18n;
